"""Turns the solver's JSON files into engine/.../FlopGto.kt.

usage: python3 combine.py DIR > FlopGto.kt
Flops of the same texture class are averaged per bucket, weighted by how often each bucket
reaches the decision. Buckets no hand reaches fall back to the decision's overall mix.
"""
import json
import os
import sys

from flops import key

NB = 20


def norm(label):
    if label.startswith("B"):
        return "B33" if int(label[1:]) < 54 else "B75"
    return label


def main(d):
    files = sorted(f for f in os.listdir(d) if f.endswith(".json"))
    acc = {}  # (spot, class, path) -> {"actions": [...], "w": [[...]], "reach": [...]}
    worst = 0.0
    for f in files:
        data = json.load(open(os.path.join(d, f)))
        worst = max(worst, data["exploitability"])
        flop = data["flop"]
        cls = key([flop[i:i + 2] for i in (0, 2, 4)])
        # how often play reaches each decision: product of the overall action frequencies on the way
        by_path = {n["path"]: n for n in data["nodes"]}
        def prob(raw):
            if not raw:
                return 1.0
            parts = raw.split("-")
            parent = by_path["-".join(parts[:-1])]
            i = parent["actions"].index(parts[-1])
            mix = sum(parent["reach"][b] * parent["freq"][b][i] for b in range(NB) if parent["freq"][b][0] >= 0) / 100
            return prob("-".join(parts[:-1])) * mix
        for n in data["nodes"]:
            path = "-".join(norm(p) for p in n["path"].split("-")) if n["path"] else ""
            acts = [norm(a) for a in n["actions"]]
            p_node = prob(n["path"])
            k = (data["spot"], cls, path)
            e = acc.setdefault(k, {"actions": [], "sum": [], "reach": [0.0] * NB, "player": n["player"], "p": 0.0, "flops": 0})
            e["p"] += p_node
            e["flops"] += 1
            for a in acts:
                if a not in e["actions"]:
                    e["actions"].append(a)
                    for row in e["sum"]:
                        row.append(0.0)
            if not e["sum"]:
                e["sum"] = [[0.0] * len(e["actions"]) for _ in range(NB)]
            for b in range(NB):
                r = n["reach"][b] * p_node
                if r <= 0 or n["freq"][b][0] < 0:
                    continue
                e["reach"][b] += r
                for i, a in enumerate(acts):
                    e["sum"][b][e["actions"].index(a)] += r * n["freq"][b][i]

    out = []
    out.append("package com.riverrunner.engine\n")
    out.append("/**")
    out.append(" * Solved flop strategies, generated by tools/flop-solve/combine.py from postflop-solver output")
    out.append(f" * ({len(files)} flops, worst exploitability {100 * worst:.2f}% of the pot). Do not edit by hand.")
    out.append(" *")
    out.append(" * Key: spot / texture class (FlopTexture.key) / flop action path. Value: actions, then for each")
    out.append(" * of the 20 strength buckets (FlopTexture.bucket) the percentage of each action.")
    out.append(" */")
    out.append("internal object FlopGtoData {")
    out.append("    val TABLE: Map<String, String> = mapOf(")
    for (spot, cls, path), e in sorted(acc.items()):
        # decisions the solver almost never reaches have meaningless strategies: leave them out
        if e["p"] / e["flops"] < 0.01:
            continue
        total = sum(e["reach"])
        overall = [sum(e["sum"][b][i] for b in range(NB)) / max(total, 1e-9) for i in range(len(e["actions"]))]
        rows = []
        for b in range(NB):
            if e["reach"][b] > 0:
                v = [x / e["reach"][b] for x in e["sum"][b]]
            else:
                v = overall
            rows.append(",".join(str(round(x)) for x in v))
        out.append(f'        "{spot}/{cls}/{path}" to "{e["player"]}|{",".join(e["actions"])}|{";".join(rows)}",')
    out.append("    )")
    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
