"""Turns the solver's JSON files into engine/.../GtoData.kt.

usage: python3 combine.py DIR > GtoData.kt

Each JSON file holds, per decision, summed action frequencies and summed reach by strength bucket
(see src/main.rs). Files are added together by key: flop and turn keys within a flop's texture
class, river keys within a flop family. Buckets that nothing reaches take the decision's overall
mix; decisions play rarely reaches are left out (their strategies are noise).
"""
import json
import os
import sys

from flops import key as texture

NB = 20
MIN_REACH = 0.002
# 64 levels per frequency, one character each
ALPHABET = "0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz+/"
CHUNK = 60000


def main(d):
    files = sorted(f for f in os.listdir(d) if f.endswith(".json"))
    acc = {}
    groups = {}  # aggregation group -> number of flops in it
    worst = {}
    for f in files:
        data = json.load(open(os.path.join(d, f)))
        spot, flop = data["spot"], data["flop"]
        worst[spot] = max(worst.get(spot, 0.0), data["exploitability"])
        cls = texture([flop[i:i + 2] for i in (0, 2, 4)])
        seen = set()
        for e in data["entries"]:
            k = e["key"]
            if k.startswith("R/"):
                group = (spot, "R", k.split("/")[1])
                full = f"{spot}/{k}"
            else:
                group = (spot, cls)
                full = f"{spot}/{cls}/{k}"
            if group not in seen:
                groups[group] = groups.get(group, 0) + 1
                seen.add(group)
            a = acc.setdefault(full, {"group": group, "player": e["player"], "actions": [], "sum": [[] for _ in range(NB)], "reach": [0.0] * NB})
            for act in e["actions"]:
                if act not in a["actions"]:
                    a["actions"].append(act)
                    for row in a["sum"]:
                        row.append(0.0)
            for b in range(NB):
                a["reach"][b] += e["reach"][b]
                for i, act in enumerate(e["actions"]):
                    a["sum"][b][a["actions"].index(act)] += e["sum"][b][i]

    lines = []
    for k in sorted(acc):
        a = acc[k]
        total = sum(a["reach"])
        if total / groups[a["group"]] < MIN_REACH:
            continue
        n = len(a["actions"])
        overall = [sum(a["sum"][b][i] for b in range(NB)) / total for i in range(n)]
        enc = []
        for b in range(NB):
            v = [x / a["reach"][b] for x in a["sum"][b]] if a["reach"][b] > 0 else overall
            s = sum(v) or 1.0
            enc.append("".join(ALPHABET[min(63, round(63 * x / s))] for x in v))
        lines.append(f"{k}\t{a['player']}\t{','.join(a['actions'])}\t{''.join(enc)}")

    text = "\n".join(lines)
    chunks = [text[i:i + CHUNK] for i in range(0, len(text), CHUNK)]
    out = ["package com.riverrunner.engine", "", "/**",
           " * Solved postflop strategies, generated by tools/flop-solve/combine.py from postflop-solver output.",
           " * " + ", ".join(f"{s}: {sum(1 for f in files if f.startswith(s + '-'))} flops, worst exploitability {100 * w:.2f}% of the pot" for s, w in sorted(worst.items())) + ".",
           f" * {len(lines)} decisions. Do not edit by hand.",
           " *",
           " * One decision per line: key, acting player (0 = out of position), actions, then for each of",
           " * the 20 strength buckets one character per action, its frequency in 64 steps (see Gto).",
           " */",
           "internal object GtoData {",
           "    val CHUNKS: Array<String> = arrayOf("]
    for c in chunks:
        out.append('        "' + c.replace("\\", "\\\\").replace("\t", "\\t").replace("\n", "\\n") + '",')
    out += ["    )", "}"]
    print("\n".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
